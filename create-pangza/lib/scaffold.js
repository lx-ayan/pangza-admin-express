"use strict";

const fs = require("fs");
const path = require("path");
const {
  resolveDependencies,
  resolveEnvLines,
  resolveDirs,
  generateMainTs,
} = require("./modules");

const ROOT = path.join(__dirname, "..");
const BASE_TEMPLATE = path.join(ROOT, "template", "base");

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeFile(filePath, content) {
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, "utf8");
}

function copyFile(src, dest) {
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
}

/**
 * @param {{
 *   targetDir: string,
 *   projectName: string,
 *   modules: string[],
 *   dbType?: string,
 * }} opts
 */
function scaffold(opts) {
  const {
    targetDir,
    projectName,
    modules,
    dbType = "mysql",
  } = opts;

  ensureDir(targetDir);

  copyFile(
    path.join(BASE_TEMPLATE, "tsconfig.json"),
    path.join(targetDir, "tsconfig.json"),
  );
  copyFile(
    path.join(BASE_TEMPLATE, "gitignore"),
    path.join(targetDir, ".gitignore"),
  );

  for (const dir of resolveDirs(modules)) {
    ensureDir(path.join(targetDir, dir));
  }

  const pkg = {
    name: projectName,
    version: "1.0.0",
    private: true,
    description: "Pangza Express app",
    scripts: {
      dev: "ts-node -r tsconfig-paths/register src/main.ts",
      build: "tsc -p tsconfig.json",
      start: "node dist/main.js",
    },
    dependencies: resolveDependencies(modules, dbType),
    devDependencies: {
      "@types/cors": "^2.8.19",
      "@types/express": "^5.0.6",
      "@types/node": "^22.0.0",
      "ts-node": "^10.9.2",
      "tsconfig-paths": "^4.2.0",
      typescript: "^5.9.3",
    },
  };

  writeFile(
    path.join(targetDir, "package.json"),
    JSON.stringify(pkg, null, 2) + "\n",
  );
  writeFile(
    path.join(targetDir, ".env.example"),
    resolveEnvLines(modules, dbType).join("\n") + "\n",
  );
  writeFile(path.join(targetDir, "src", "main.ts"), generateMainTs(modules));

  writeFile(
    path.join(targetDir, "README.md"),
    `# ${projectName}

Generated by \`create-pangza init\`.

## Modules

${modules.length ? modules.map((m) => `- ${m}`).join("\n") : "- (core only)"}

${modules.includes("orm") ? `Database: **${dbType}**\n` : ""}
## Run

\`\`\`bash
cp .env.example .env
npm install
npm run dev
\`\`\`

需要 Redis / 数据库时，请在入口 \`registry(EnableRedis())\` / \`registry(EnableOrm())\`（脚手架勾选对应模块时已自动写入）。
`,
  );
}

module.exports = { scaffold };
